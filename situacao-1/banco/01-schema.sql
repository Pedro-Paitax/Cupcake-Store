BEGIN;

-- ---------------------------------------------------------------------
-- usuario: clientes e administradores
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    nome        varchar(100) NOT NULL,
    email       varchar(150) NOT NULL,
    senha_hash  varchar(255) NOT NULL,
    telefone    varchar(11)  NOT NULL,
    endereco    varchar(200),
    perfil      varchar(10)  NOT NULL DEFAULT 'cliente',
    criado_em   timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('cliente', 'admin'))
);
CREATE UNIQUE INDEX uq_usuario_email ON usuario (email);

COMMENT ON TABLE  usuario            IS 'Pessoas com acesso ao sistema: clientes (app/loja) e administradores (painel).';
COMMENT ON COLUMN usuario.id         IS 'Identificador do usuário (gerado automaticamente).';
COMMENT ON COLUMN usuario.nome       IS 'Nome completo.';
COMMENT ON COLUMN usuario.email      IS 'E-mail de login, sempre em minúsculas. Único.';
COMMENT ON COLUMN usuario.senha_hash IS 'Hash PBKDF2 (ASP.NET Identity) da senha. A senha nunca é gravada em texto puro.';
COMMENT ON COLUMN usuario.telefone   IS 'Telefone com DDD, somente dígitos (10 ou 11).';
COMMENT ON COLUMN usuario.endereco   IS 'Endereço padrão de entrega (opcional no cadastro).';
COMMENT ON COLUMN usuario.perfil     IS 'Papel no sistema: cliente ou admin.';
COMMENT ON COLUMN usuario.criado_em  IS 'Data/hora do cadastro (UTC).';

-- ---------------------------------------------------------------------
-- cupcake: itens do cardápio
-- ---------------------------------------------------------------------
CREATE TABLE cupcake (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    nome        varchar(80)   NOT NULL,
    descricao   varchar(500)  NOT NULL,
    preco       numeric(10,2) NOT NULL,
    imagem      varchar(300)  NOT NULL,
    ativo       boolean       NOT NULL DEFAULT true,
    criado_em   timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT pk_cupcake PRIMARY KEY (id),
    CONSTRAINT ck_cupcake_preco CHECK (preco > 0)
);
CREATE UNIQUE INDEX uq_cupcake_nome ON cupcake (nome);

COMMENT ON TABLE  cupcake           IS 'Cardápio. Cupcakes não são excluídos (estão em pedidos antigos): são desativados.';
COMMENT ON COLUMN cupcake.id        IS 'Identificador do cupcake.';
COMMENT ON COLUMN cupcake.nome      IS 'Nome exibido no cardápio. Único.';
COMMENT ON COLUMN cupcake.descricao IS 'Descrição de massa, recheio e cobertura.';
COMMENT ON COLUMN cupcake.preco     IS 'Preço atual em reais. Maior que zero.';
COMMENT ON COLUMN cupcake.imagem    IS 'Nome do recurso de imagem do app (ex.: chocolate) ou URL https.';
COMMENT ON COLUMN cupcake.ativo     IS 'Se false, não aparece no cardápio nem pode ser comprado.';
COMMENT ON COLUMN cupcake.criado_em IS 'Data/hora de inclusão no cardápio (UTC).';

-- ---------------------------------------------------------------------
-- pedido: cabeçalho do pedido
-- ---------------------------------------------------------------------
CREATE TABLE pedido (
    id               integer GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       integer       NOT NULL,
    status           varchar(20)   NOT NULL DEFAULT 'Recebido',
    taxa_entrega     numeric(10,2) NOT NULL,
    endereco_entrega varchar(200)  NOT NULL,
    criado_em        timestamp with time zone NOT NULL DEFAULT now(),
    atualizado_em    timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT pk_pedido PRIMARY KEY (id),
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT ck_pedido_status CHECK (status IN ('Recebido', 'EmPreparo', 'SaiuParaEntrega', 'Entregue', 'Cancelado')),
    CONSTRAINT ck_pedido_taxa CHECK (taxa_entrega >= 0)
);
CREATE INDEX ix_pedido_usuario ON pedido (usuario_id);
CREATE INDEX ix_pedido_status  ON pedido (status);

COMMENT ON TABLE  pedido                  IS 'Pedido feito por um cliente. Subtotal e total são calculados a partir dos itens (3FN).';
COMMENT ON COLUMN pedido.id               IS 'Número do pedido.';
COMMENT ON COLUMN pedido.usuario_id       IS 'Cliente que fez o pedido (FK usuario.id).';
COMMENT ON COLUMN pedido.status           IS 'Recebido → EmPreparo → SaiuParaEntrega → Entregue; ou Cancelado.';
COMMENT ON COLUMN pedido.taxa_entrega     IS 'Taxa de entrega cobrada neste pedido (histórico).';
COMMENT ON COLUMN pedido.endereco_entrega IS 'Endereço de entrega deste pedido (pode diferir do cadastro).';
COMMENT ON COLUMN pedido.criado_em        IS 'Data/hora do pedido (UTC).';
COMMENT ON COLUMN pedido.atualizado_em    IS 'Data/hora da última mudança de status (UTC).';

-- ---------------------------------------------------------------------
-- item_pedido: tabela associativa pedido × cupcake (N:N)
-- ---------------------------------------------------------------------
CREATE TABLE item_pedido (
    id             integer GENERATED BY DEFAULT AS IDENTITY,
    pedido_id      integer       NOT NULL,
    cupcake_id     integer       NOT NULL,
    quantidade     integer       NOT NULL,
    preco_unitario numeric(10,2) NOT NULL,
    CONSTRAINT pk_item_pedido PRIMARY KEY (id),
    CONSTRAINT fk_item_pedido_pedido  FOREIGN KEY (pedido_id)  REFERENCES pedido (id)  ON DELETE CASCADE,
    CONSTRAINT fk_item_pedido_cupcake FOREIGN KEY (cupcake_id) REFERENCES cupcake (id) ON DELETE RESTRICT,
    CONSTRAINT ck_item_quantidade CHECK (quantidade BETWEEN 1 AND 50),
    CONSTRAINT ck_item_preco CHECK (preco_unitario > 0)
);
CREATE UNIQUE INDEX uq_item_pedido_cupcake ON item_pedido (pedido_id, cupcake_id);
CREATE INDEX ix_item_pedido_cupcake ON item_pedido (cupcake_id);

COMMENT ON TABLE  item_pedido                IS 'Cupcakes de cada pedido. Um cupcake aparece no máximo uma vez por pedido.';
COMMENT ON COLUMN item_pedido.id             IS 'Identificador do item.';
COMMENT ON COLUMN item_pedido.pedido_id      IS 'Pedido ao qual o item pertence (FK pedido.id).';
COMMENT ON COLUMN item_pedido.cupcake_id     IS 'Cupcake comprado (FK cupcake.id).';
COMMENT ON COLUMN item_pedido.quantidade     IS 'Quantidade (1 a 50).';
COMMENT ON COLUMN item_pedido.preco_unitario IS 'Preço do cupcake no momento da compra (não muda se o cardápio for reajustado).';

-- ---------------------------------------------------------------------
-- Visão com os valores derivados de cada pedido (usada em relatórios)
-- ---------------------------------------------------------------------
CREATE VIEW vw_pedido_resumo AS
SELECT p.id,
       p.usuario_id,
       u.nome                                         AS cliente,
       p.status,
       p.criado_em,
       COALESCE(SUM(i.quantidade), 0)                 AS quantidade_itens,
       COALESCE(SUM(i.quantidade * i.preco_unitario), 0)::numeric(10,2)                  AS subtotal,
       p.taxa_entrega,
       (COALESCE(SUM(i.quantidade * i.preco_unitario), 0) + p.taxa_entrega)::numeric(10,2) AS total
FROM pedido p
JOIN usuario u          ON u.id = p.usuario_id
LEFT JOIN item_pedido i ON i.pedido_id = p.id
GROUP BY p.id, u.nome;

COMMENT ON VIEW vw_pedido_resumo IS 'Pedido com subtotal, total e quantidade de itens calculados.';

COMMIT;
